#!/bin/bash
# usage: stages.sh <cpu.pb.gz>  -> share of total CPU per stage (focus on stack frame regex)
f=$1
stage() { r=$(env -u GOROOT go tool pprof -top -nodecount=100000 -nodefraction=0 -edgefraction=0 -focus="$2" "$f" 2>/dev/null | grep -m1 "Showing nodes accounting for" | sed -E 's/.*for ([^,]+), ([0-9.]+%).*/\1 \2/'); printf "%-48s %s\n" "$1" "${r:-0 0%}"; }
env -u GOROOT go tool pprof -top -nodecount=1 "$f" 2>/dev/null | grep -E "Duration"
stage "Pod.Render total"                    'render\.\(\*Pod\)\.Render'
stage "  FromUnstructured anywhere"         'FromUnstructured'
stage "model1.Hydrate (all)"                'model1\.Hydrate'
stage "informer/lister List (watch.Factory.List)" 'watch\.\(\*Factory\)\.List|cache\.\(\*Lister|ListAllByNamespace|listers'
stage "dao List (dao.*List)"                'dao\.\(\*\w+\)\.List'
stage "model.Table.refresh/reconcile"       'model\.\(\*Table\)\.(refresh|reconcile)'
stage "TableData.Update / delta"            'model1\.\(\*TableData\)\.(Update|Render)$|NewDeltaRow|DeltaRow'
stage "TableData.Clone / Peek"              'model1\.\(\*TableData\)\.Clone|model\.\(\*Table\)\.Peek|RowEvents\)\.Clone'
stage "TableData.Filter"                    'model1\.\(\*TableData\)\.Filter'
stage "ui.Table.UpdateUI"                   'ui\.\(\*Table\)\.UpdateUI'
stage "  Sort (model1)"                     'model1\.\(\*RowEvents\)\.Sort'
stage "  ComputeMaxColumns"                 'MaxColumn'
stage "  buildRow"                          'ui\.\(\*Table\)\.buildRow'
stage "  tview SetCell"                     'tview\.\(\*Table\)\.SetCell'
stage "  UpdateTitle/AsThousands"           'UpdateTitle|AsThousands'
stage "tcell/tview draw (Draw)"             'tview\.\(\*Application\)\.draw|tview\.\(\*Table\)\.Draw|tcell.*Show'
stage "GC bg mark (gcBgMarkWorker)"         'runtime\.gcBgMarkWorker'
stage "mallocgc (all)"                      'runtime\.mallocgc$'
stage "GC assist (gcAssistAlloc)"           'gcAssistAlloc'
stage "json (encoding/json any)"            'encoding/json'
stage "netpoll/scheduler idle (kevent/usleep)" 'runtime\.(kevent|usleep)$'
stage "  FromUnstructured under Pod.Render"     'render\.\(\*Pod\)\.defaultRow;.*FromUnstructured' 
stage "parallelRender goroutines (all)"     'model1\.parallelRender'
stage "tview event loop (Application.Run)"  'tview\.\(\*Application\)\.Run'
stage "ui.Table.SortColCmd/sort handlers"   'ui\.\(\*Table\)\.(SortColCmd|sortCol)|view\.\(\*Table\)\.(SortColCmd|sortCol)|SortColCmd'
stage "TableData.Filter rx/fuzzy"           'model1\.\(\*TableData\)\.(Filter|rxFilter|fuzzyFilter)'
stage "regexp"                              '^regexp\.'
stage "ui.Table.Refresh/doUpdate (non-tick)" 'ui\.\(\*Table\)\.(Refresh|doUpdate)'
stage "AsThousands/message.NewPrinter"      'AsThousands|message\.NewPrinter'
stage "Peek (model.Table.Peek)"             'model\.\(\*Table\)\.Peek'
